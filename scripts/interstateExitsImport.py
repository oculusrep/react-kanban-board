# Interstate exit badges: OpenStreetMap -> SQL for public.interstate_exit.
# Overpass API docs: https://wiki.openstreetmap.org/wiki/Overpass_API
# Data (c) OpenStreetMap contributors, ODbL.
#
# Usage (from repo root):
#   python3 -I scripts/interstateExitsImport.py <work_dir> 85 20 > /tmp/exits.sql
#   psql "$DATABASE_URL" -v ON_ERROR_STOP=1 --single-transaction -f /tmp/exits.sql
# Reloads only the highways named (DELETE + INSERT per highway).
import json, math, subprocess, sys, time, os

work = sys.argv[1]; highways = sys.argv[2:]
os.makedirs(work, exist_ok=True)
MERGE_KM = 6.0  # per-direction off-ramps diverge up to ~4 km apart; midpoint = interchange

def fetch(hw):
    path = f'{work}/i{hw}.json'
    if os.path.exists(path):
        return json.load(open(path))['elements']
    q = (f'[out:json][timeout:90];area["ISO3166-2"="US-GA"]->.ga;'
         f'way["highway"="motorway"]["ref"~"(^|;) ?I {hw}(;|$)"](area.ga)->.w;'
         f'node(w.w)["highway"="motorway_junction"];out body;')
    for attempt in range(5):
        r = subprocess.run(['curl', '-s', '--max-time', '120', '-A', 'OVIS-exit-import/1.0',
                            'https://overpass-api.de/api/interpreter', '--data-urlencode', f'data={q}'],
                           capture_output=True, text=True).stdout
        try:
            d = json.loads(r); open(path, 'w').write(r); return d['elements']
        except ValueError:
            time.sleep(20)
    raise SystemExit(f'Overpass failed for I-{hw}')

def km(a, b):
    la1, lo1, la2, lo2 = map(math.radians, (a[0], a[1], b[0], b[1]))
    h = math.sin((la2-la1)/2)**2 + math.cos(la1)*math.cos(la2)*math.sin((lo2-lo1)/2)**2
    return 6371 * 2 * math.asin(math.sqrt(h))

out = ['-- generated by scripts/interstateExitsImport.py']
for hw in highways:
    nodes = [e for e in fetch(hw) if e.get('tags', {}).get('ref')]
    groups = {}  # ref -> list of clusters [[(lat,lng,id), ...]]
    for e in nodes:
        ref = e['tags']['ref'].strip()
        if not any(ch.isdigit() for ch in ref):
            continue  # e.g. 'HOV Exit'
        pt = (e['lat'], e['lon'], e['id'])
        clusters = groups.setdefault(ref, [])
        for c in clusters:
            if km(c[0], pt) <= MERGE_KM:
                c.append(pt); break
        else:
            clusters.append([pt])
    hwname = f'I-{hw}'
    out.append(f"DELETE FROM public.interstate_exit WHERE highway = '{hwname}';")
    n = 0
    for ref, clusters in groups.items():
        for c in clusters:
            lat = sum(p[0] for p in c) / len(c); lng = sum(p[1] for p in c) / len(c)
            ids = ','.join(str(p[2]) for p in c)
            safe_ref = ref.replace("'", "''")
            out.append(f"INSERT INTO public.interstate_exit (highway, exit_ref, latitude, longitude, osm_node_ids) "
                       f"VALUES ('{hwname}', '{safe_ref}', {lat:.7f}, {lng:.7f}, '{{{ids}}}');")
            n += 1
    print(f'{hwname}: {len(nodes)} numbered nodes -> {n} badges', file=sys.stderr)
print('\n'.join(out))
